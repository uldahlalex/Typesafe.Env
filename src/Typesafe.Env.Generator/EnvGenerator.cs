using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Typesafe.Env.Generator;

// Turns the keys in the repository's .env into a typed Env class, so configuration is used as env.PGHOST instead of
// config["PGHOST"]: a key that is added to .env shows up in code, one that is removed or renamed breaks the build.
// The development value decides the type: digits are an int, an empty value is optional (string?), anything else is a
// required string. .env.production must have the same keys.
[Generator]
public sealed class EnvGenerator : IIncrementalGenerator
{
    private static readonly Regex Line = new(@"^\s*(?<key>[^#=\s][^=]*?)\s*=\s*(?<value>.*?)\s*$");
    private static readonly Regex Identifier = new(@"^[A-Za-z_][A-Za-z0-9_]*$");

    private static readonly DiagnosticDescriptor InvalidKey = new(
        "TSENV001",
        "Invalid .env key",
        "The .env key '{0}' can't be a C# property name; use letters, digits and _ (__ for a nested key)",
        "Configuration",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var keys = context.AdditionalTextsProvider
            .Where(static text => Path.GetFileName(text.Path) == ".env")
            .Select(static (text, cancellationToken) => Parse(text.GetText(cancellationToken)?.ToString() ?? ""))
            .Collect()
            .Select(static (files, _) => files.SelectMany(static file => file).ToImmutableArray());

        var rootNamespace = context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) => options.GlobalOptions.TryGetValue("build_property.RootNamespace", out var value) ? value : "App");

        context.RegisterSourceOutput(keys.Combine(rootNamespace), static (context, input) => Emit(context, input.Left, input.Right));
    }

    private static IEnumerable<(string Key, string Value)> Parse(string text) =>
        text.Split('\n')
            .Select(static line => Line.Match(line))
            .Where(static match => match.Success)
            .Select(static match => (match.Groups["key"].Value, match.Groups["value"].Value));

    private static void Emit(SourceProductionContext context, ImmutableArray<(string Key, string Value)> entries, string rootNamespace)
    {
        // Only projects that see a .env get Env; an empty one in a referencing project (tests) would hide the real one.
        if (entries.IsEmpty)
            return;

        foreach (var (key, _) in entries.Where(static entry => !Identifier.IsMatch(entry.Key)))
            context.ReportDiagnostic(Diagnostic.Create(InvalidKey, Location.None, key));

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated by Typesafe.Env from .env />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System.Linq;");
        builder.AppendLine($"namespace {rootNamespace};");
        builder.AppendLine();
        builder.AppendLine("public sealed class Env(Microsoft.Extensions.Configuration.IConfiguration configuration)");
        builder.AppendLine("{");

        var valid = entries.Where(static entry => Identifier.IsMatch(entry.Key)).ToList();
        foreach (var (key, value) in valid)
            builder.AppendLine(Property(key, value));

        var required = string.Join(", ", valid.Where(static entry => entry.Value.Length > 0).Select(static entry => $"\"{entry.Key}\""));
        var numbers = string.Join(", ", valid.Where(static entry => entry.Value.Length > 0 && entry.Value.All(char.IsDigit)).Select(static entry => $"\"{entry.Key}\""));
        builder.AppendLine();
        builder.AppendLine("    // Called at startup, so a missing or malformed key stops the app there instead of on first use.");
        builder.AppendLine("    public void Validate()");
        builder.AppendLine("    {");
        builder.AppendLine($"        var missing = new string[] {{ {required} }}.Where(key => Optional(key) is null).Select(key => $\"{{key}} is missing\");");
        builder.AppendLine($"        var notNumbers = new string[] {{ {numbers} }}.Where(key => Optional(key) is {{ }} value && !int.TryParse(value, out _)).Select(key => $\"{{key}} is not a number\");");
        builder.AppendLine("        var problems = missing.Concat(notNumbers).ToArray();");
        builder.AppendLine("        if (problems.Length > 0)");
        builder.AppendLine("            throw new System.InvalidOperationException(");
        builder.AppendLine("                $\"Configuration (.env in development, .env.production in production): {string.Join(\", \", problems)}.\");");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private string? Optional(string key) => configuration[key.Replace(\"__\", \":\")] is { Length: > 0 } value ? value : null;");
        builder.AppendLine();
        builder.AppendLine("    private string Required(string key) => Optional(key)");
        builder.AppendLine("        ?? throw new System.InvalidOperationException($\"{key} must be set (.env in development, .env.production in production).\");");
        builder.AppendLine("}");

        context.AddSource("Env.g.cs", builder.ToString());
    }

    private static string Property(string key, string value)
    {
        if (value.Length == 0)
            return $"    public string? {key} => Optional(\"{key}\");";

        if (value.All(char.IsDigit))
            return $"    public int {key} => int.Parse(Required(\"{key}\"));";

        return $"    public string {key} => Required(\"{key}\");";
    }
}
